/**
 * Lists the home-banner photographs that actually exist in /public/stories and
 * writes them into a constant the app imports.
 *
 * Runs before every build. Without it the carousel would ask the browser for
 * photos that aren't there yet and take a failed request on each one; with it,
 * adding a photo is still just dropping a file in — the next build picks it up.
 * See docs/BANNER-IMAGES.md.
 */
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "public", "stories");
const out = path.join(process.cwd(), "src", "lib", "story-manifest.ts");

let files = [];
try {
  files = readdirSync(dir)
    .filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f))
    .sort();
} catch {
  // No folder yet — that's fine, the painted banners are used.
}

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/story-manifest.mjs — do not edit by hand.\n` +
    `// Add or remove files in public/stories and rebuild.\n` +
    `export const STORY_IMAGES: readonly string[] = ${JSON.stringify(
      files.map((f) => `/stories/${f}`),
      null,
      2,
    )} as const;\n`,
);
console.log(`story-manifest: ${files.length} banner photo(s) found`);
